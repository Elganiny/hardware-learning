"""Copy the latest KiCad files from the working folders into this repo and regenerate the docs.

    python tools/update_docs.py            # all projects
    python tools/update_docs.py P01        # one project

For each project it copies .kicad_pro/.kicad_sch/.kicad_pcb into projects/<name>/kicad/ and writes into
projects/<name>/docs/: schematic.pdf, pcb_top.png, pcb_bottom.png, bom.csv and checks.md (ERC + DRC summary).
The working folders (~/Code/my_boards by default) stay the place where you design; this repo is the
published copy. Run it after every finished change, then review and commit.
Override the locations with the environment variables KICAD_CLI and MY_BOARDS if they differ.
"""
import os
import re
import shutil
import subprocess
import sys

KICAD_CLI = os.environ.get("KICAD_CLI") or os.path.join(
    os.environ.get("LOCALAPPDATA", ""), "Programs", "KiCad", "10.0", "bin", "kicad-cli.exe")
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORK = os.environ.get("MY_BOARDS") or os.path.join(os.path.expanduser("~"), "Code", "my_boards")

# repo folder -> (working folder, KiCad project name)
PROJECTS = {
    "P00-mini-dashboard-v1": (os.path.join(WORK, "P00_mini_dashboard", "mini_dashboard"), "mini_dashboard"),
    "P01-mini-dashboard-v2": (os.path.join(WORK, "P01_mini_dashboard_v2", "mini_dashboard_v2"), "mini_dashboard_v2"),
}


def cli(*args):
    return subprocess.run([KICAD_CLI, *args], capture_output=True, text=True)


def summary(report, kind):
    txt = open(report, encoding="utf8", errors="replace").read() if os.path.exists(report) else ""
    if kind == "erc":
        m = re.search(r"ERC messages: (\d+)\s+Errors (\d+)\s+Warnings (\d+)", txt)
        return "%s errors, %s warnings" % (m.group(2), m.group(3)) if m else "not run"
    found = dict((k, v) for v, k in re.findall(r"Found (\d+) (DRC violations|unconnected pads|Footprint errors)", txt))
    return ", ".join("%s %s" % (v, k) for k, v in found.items()) or "not run"


def update(folder):
    src, name = PROJECTS[folder]
    dst = os.path.join(REPO, "projects", folder)
    kdir, ddir = os.path.join(dst, "kicad"), os.path.join(dst, "docs")
    os.makedirs(kdir, exist_ok=True)
    os.makedirs(ddir, exist_ok=True)
    for ext in (".kicad_pro", ".kicad_sch", ".kicad_pcb"):
        shutil.copy2(os.path.join(src, name + ext), os.path.join(kdir, name + ext))
    sch, pcb = os.path.join(kdir, name + ".kicad_sch"), os.path.join(kdir, name + ".kicad_pcb")
    cli("sch", "export", "pdf", "-o", os.path.join(ddir, "schematic.pdf"), sch)
    cli("sch", "export", "bom", "-o", os.path.join(ddir, "bom.csv"), sch)
    cli("pcb", "render", "--side", "top", "--width", "1200", "--height", "1000", "-o", os.path.join(ddir, "pcb_top.png"), pcb)
    cli("pcb", "render", "--side", "bottom", "--width", "1200", "--height", "1000", "-o", os.path.join(ddir, "pcb_bottom.png"), pcb)
    erc, drc = os.path.join(ddir, "_erc.rpt"), os.path.join(ddir, "_drc.rpt")
    cli("sch", "erc", "-o", erc, sch)
    cli("pcb", "drc", "--schematic-parity", "-o", drc, pcb)
    with open(os.path.join(ddir, "checks.md"), "w", encoding="utf8") as f:
        f.write("# Automatic checks (KiCad 10, regenerated by tools/update_docs.py)\n\n")
        f.write("| Check | Result |\n|---|---|\n")
        f.write("| ERC | %s |\n" % summary(erc, "erc"))
        f.write("| DRC with schematic parity | %s |\n" % summary(drc, "drc"))
    for r in (erc, drc):
        if os.path.exists(r):
            os.remove(r)
    print("updated", folder)


if __name__ == "__main__":
    wanted = sys.argv[1:]
    for folder in PROJECTS:
        if not wanted or any(folder.startswith(w) for w in wanted):
            update(folder)
